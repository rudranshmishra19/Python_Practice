# This script demonstrates the use of literal backslashes in Python strings

# Using a single backslash
single_backslash = "This is a single backslash: \\"
print(single_backslash)

# Using double backslashes
double_backslash = "This is a double backslash: \\\\"
print(double_backslash)

# Using raw strings to avoid escaping backslashes
raw_string = r"This is a raw string with a single backslash: \ "
print(raw_string)

# Using triple quotes for multi-line strings with backslashes
multi_line_string = """This is a multi-line string with a backslash:
\\
"""
print(multi_line_string)


